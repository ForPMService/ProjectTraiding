using System;

namespace ProjectTraiding.Moex.Loading
{
    /// <summary>
    /// Приёмник хода загрузки. Писатель рядов вызывает его на каждом сбросе пачки, сообщая
    /// накопленное число прочитанных строк и метку времени последней строки пачки. Куда эти
    /// сведения денутся — забота реализации; писатель рядов о хранилище не знает. Делегаты
    /// в проекте запрещены, поэтому отдача идёт через этот интерфейс, а не через обратный вызов.
    /// </summary>
    public interface ILoadProgressReporter
    {
        /// <summary>
        /// Принять сведения о ходе одной задачи: сколько строк прочитано на данный момент
        /// и до какой метки времени рынка дошла загрузка.
        /// </summary>
        Task ReportAsync(Guid taskId, long rowsRead, DateTime lastSourceTime, CancellationToken ct);
    }
}
