using System.Buffers;
using ProtoBuf;
using ProtoBuf.Meta;

namespace ProjectTraiding.Moex.StorageBase.ClickHouse;

/// <summary>
/// Typed row for historical MOEX candles across the interval-specific
/// <c>moex_candles</c> tables. Begin and End are fractional Unix seconds and
/// use the ClickHouse Protobuf schema declared below.
/// </summary>
[ProtoContract]
public struct CandleRow
{
    [ProtoMember(1)]
    public string Secid { get; set; }

    [ProtoMember(2)]
    public double? Open { get; set; }

    [ProtoMember(3)]
    public double? Close { get; set; }

    [ProtoMember(4)]
    public double? High { get; set; }

    [ProtoMember(5)]
    public double? Low { get; set; }

    [ProtoMember(6)]
    public double? Value { get; set; }

    [ProtoMember(7)]
    public double? Volume { get; set; }

    [ProtoMember(8)]
    public double Begin { get; set; }

    [ProtoMember(9)]
    public double? End { get; set; }

    [ProtoMember(10)]
    public uint IngestPriority { get; set; }
}

[ProtoModel]
[ProtoSerializable(typeof(CandleRow))]
public partial class MarketProtobufModel : TypeModel
{
}

/// <summary>
/// ClickHouse's autogenerated DateTime64 schema uses uint64, which the server
/// reads as whole seconds. This schema uses double Unix seconds so scale-3
/// DateTime64 values retain their milliseconds.
/// </summary>
public static class CandleProtobufSchema
{
    public const string MessageName = "CandleRow";

    public const string Definition = """
        syntax = "proto3";
        message CandleRow {
          bytes secid = 1;
          double open = 2;
          double close = 3;
          double high = 4;
          double low = 5;
          double value = 6;
          double volume = 7;
          double begin = 8;
          double end = 9;
          uint32 ingest_priority = 10;
        }
        """;
}

/// <summary>
/// Writes one length-delimited candle message to a batch buffer.
/// </summary>
public static class CandleProtobufBatchWriter
{
    public static void Append(IBufferWriter<byte> destination, in CandleRow row)
    {
        using MeasureState<CandleRow> measured = MarketProtobufModel.Instance.Measure(row);
        WriteVarint(destination, checked((ulong)measured.Length));
        measured.Serialize(destination);
    }

    private static void WriteVarint(IBufferWriter<byte> destination, ulong value)
    {
        Span<byte> span = destination.GetSpan(10);
        int length = 0;

        while (value >= 0x80)
        {
            span[length++] = (byte)(value | 0x80);
            value >>= 7;
        }

        span[length++] = (byte)value;
        destination.Advance(length);
    }
}

/// <summary>
/// Converts MOEX's Moscow wall-clock labels to fractional Unix seconds for
/// the explicit ClickHouse Protobuf schema used with DateTime64(3).
/// </summary>
public static class CandleDateTime64
{
    private static readonly TimeZoneInfo MoscowTimeZone =
        TimeZoneInfo.FindSystemTimeZoneById("Europe/Moscow");

    public static double ToUnixSeconds(DateTime moscowWallClock)
    {
        if (moscowWallClock.Kind != DateTimeKind.Unspecified)
        {
            throw new ArgumentException(
                "MOEX candle timestamps must be Moscow wall-clock values with Unspecified kind.",
                nameof(moscowWallClock));
        }

        if (MoscowTimeZone.IsInvalidTime(moscowWallClock)
            || MoscowTimeZone.IsAmbiguousTime(moscowWallClock))
        {
            throw new ArgumentException(
                "The Moscow wall-clock timestamp does not identify one unambiguous instant.",
                nameof(moscowWallClock));
        }

        DateTime utc = TimeZoneInfo.ConvertTimeToUtc(moscowWallClock, MoscowTimeZone);
        long unixMilliseconds = new DateTimeOffset(utc).ToUnixTimeMilliseconds();
        if (unixMilliseconds < 0)
        {
            throw new ArgumentOutOfRangeException(
                nameof(moscowWallClock), "DateTime64 values before the Unix epoch are unsupported.");
        }

        return unixMilliseconds / 1000.0;
    }

    public static double? ToUnixSeconds(DateTime? moscowWallClock)
        => moscowWallClock.HasValue
            ? ToUnixSeconds(moscowWallClock.Value)
            : null;
}
