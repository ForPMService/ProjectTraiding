using ClickHouse.Driver;
using System;
using System.Buffers;
using System.Collections.Generic;
using System.Diagnostics;
using System.Net.Http;
using System.Text;
using ProjectTraiding.Moex.Infrastructure.Telemetry;

namespace ProjectTraiding.Moex.StorageBase.ClickHouse
{
    /// <summary>
    /// Исполнитель одной вставки в ClickHouse: пишет готовую пачку строк одним INSERT
    /// в форматах RowBinary и Protobuf. Общий механизм для всех рядов —
    /// таблица, столбцы и строки приходят параметрами.
    /// Содержимое строк не проверяет: парсер уже признал данные корректными.
    /// </summary>
    public sealed class ClickHouseInsertExecutor
    {
        // Значения настроек имеют тип объекта: числовые литералы упаковывались бы в кучу
        // на каждую вставку. Значение постоянно, поэтому упаковано один раз.
        private static readonly object DisabledSetting = 0;
        private static readonly object EnabledSetting = 1;

        private readonly ClickHouseClient _client;
        private readonly ILogger<ClickHouseInsertExecutor> _logger;

        public ClickHouseInsertExecutor(ClickHouseClient client, ILogger<ClickHouseInsertExecutor> logger)
        {
            _client = client;
            _logger = logger;
        }

        /// <summary>
        /// Пишет одну пачку одним INSERT. Возвращает число вставленных строк.
        /// </summary>
        public Task<long> InsertAsync(
            string table,
            IReadOnlyList<string> columns,
            IReadOnlyDictionary<string, string> columnTypes,
            IReadOnlyList<object?[]> rows,
            StorageInsertContext insertContext,
            CancellationToken ct)
        {
            if (rows.Count == 0)
                return Task.FromResult(0L);

            // ColumnTypes задан явно → драйвер не шлёт SELECT ... WHERE 1=0 перед вставкой.
            InsertOptions options = new InsertOptions
            {
                BatchSize = rows.Count,
                MaxDegreeOfParallelism = 1,
                ColumnTypes = columnTypes,
                CustomSettings = CreateFlowSettings(insertContext),
                Compressor = null,    
            };

            return ExecuteInsertAsync(
                table,
                rows.Count,
                insertContext,
                token => _client.InsertBinaryAsync(table, columns, rows, options, token),
                ct);
        }

        /// <summary>
        /// Serializes one typed batch with its generated protobuf model and sends it
        /// as one HTTP INSERT in ClickHouse Protobuf format. A successful response
        /// reports the number of rows in the request; it is not a server-side recount.
        /// </summary>
        public Task<long> InsertProtobufAsync<T>(
            string table,
            IReadOnlyList<string> columns,
            string protobufSchema,
            string messageName,
            IReadOnlyList<T> rows,
            Action<IBufferWriter<byte>, T> serializeRow,
            StorageInsertContext insertContext,
            CancellationToken ct)
            where T : struct
        {
            ArgumentException.ThrowIfNullOrWhiteSpace(table);
            ArgumentNullException.ThrowIfNull(columns);
            ArgumentException.ThrowIfNullOrWhiteSpace(protobufSchema);
            ArgumentException.ThrowIfNullOrWhiteSpace(messageName);
            ArgumentNullException.ThrowIfNull(rows);
            ArgumentNullException.ThrowIfNull(serializeRow);

            if (columns.Count == 0)
                throw new ArgumentException("At least one target column is required.", nameof(columns));

            int rowCount = rows.Count;
            if (rowCount == 0)
                return Task.FromResult(0L);

            string sql = $"INSERT INTO {table} ({string.Join(", ", columns)}) FORMAT Protobuf";
            Dictionary<string, object> customSettings = CreateFlowSettings(insertContext);
            customSettings["format_schema_source"] = "string";
            customSettings["format_schema"] = protobufSchema;
            customSettings["format_schema_message_name"] = messageName;
            customSettings["format_protobuf_use_autogenerated_schema"] = DisabledSetting;

            QueryOptions options = new QueryOptions
            {
                CustomSettings = customSettings,
            };

            return ExecuteInsertAsync(
                table,
                rowCount,
                insertContext,
                async token =>
                {
                    var buffer = new ArrayBufferWriter<byte>();
                    for (int index = 0; index < rowCount; index++)
                    {
                        token.ThrowIfCancellationRequested();
                        serializeRow(buffer, rows[index]);
                    }

                    using HttpResponseMessage response = await _client.PostStreamAsync(
                        sql,
                        async (stream, streamToken) =>
                        {
                            await stream.WriteAsync(buffer.WrittenMemory, streamToken).ConfigureAwait(false);
                        },
                        isCompressed: false,
                        token: token,
                        queryOptions: options).ConfigureAwait(false);

                    response.EnsureSuccessStatusCode();
                    return rowCount;
                },
                ct);
        }

        /// <summary>
        /// Отправляет готовую пачку length-delimited Protobuf одним INSERT.
        /// Успешный результат — число строк, переданных в запросе.
        /// </summary>
        public async Task<long> InsertProtobufAsync(
            string table,
            IReadOnlyList<string> columns,
            ReadOnlyMemory<byte> body,
            int rowCount,
            StorageInsertContext insertContext,
            CancellationToken cancellationToken)
        {
            ArgumentException.ThrowIfNullOrWhiteSpace(table);
            ArgumentNullException.ThrowIfNull(columns);

            if (columns.Count == 0)
                throw new ArgumentException("At least one target column is required.", nameof(columns));

            if (rowCount < 0)
                throw new ArgumentOutOfRangeException(nameof(rowCount), "Row count cannot be negative.");

            if ((rowCount == 0) != body.IsEmpty)
                throw new ArgumentException("The row count and Protobuf body must both be empty or non-empty.", nameof(body));

            if (rowCount == 0)
                return 0;

            string sql = $"INSERT INTO {table} ({string.Join(", ", columns)}) FORMAT Protobuf";
            Dictionary<string, object> customSettings = CreateFlowSettings(insertContext);
            customSettings["format_protobuf_use_autogenerated_schema"] = EnabledSetting;

            QueryOptions options = new QueryOptions
            {
                CustomSettings = customSettings,
            };

            ClickHouseWriterLogMessages.WriteStarted(_logger, table, rowCount);

            try
            {
                using (HttpResponseMessage response = await _client.PostStreamAsync(
                    sql,
                    async (stream, streamToken) =>
                    {
                        await stream.WriteAsync(body, streamToken).ConfigureAwait(false);
                    },
                    isCompressed: false,
                    token: cancellationToken,
                    queryOptions: options).ConfigureAwait(false))
                {
                    response.EnsureSuccessStatusCode();
                }

                RecordInsert(in insertContext, MoexOutcomes.Success, rowCount);
                return rowCount;
            }
            catch (Exception ex)
            {
                ClickHouseWriterLogMessages.WriteFailed(_logger, ex, table, ex.GetType().Name);

                string outcome = ex is OperationCanceledException
                    ? MoexOutcomes.Cancelled
                    : MoexOutcomes.Error;

                RecordInsert(in insertContext, outcome, null);
                throw;
            }
        }

        private async Task<long> ExecuteInsertAsync(
            string table,
            int rowCount,
            StorageInsertContext insertContext,
            Func<CancellationToken, Task<long>> insertOperation,
            CancellationToken ct)
        {
            ClickHouseWriterLogMessages.WriteStarted(_logger, table, rowCount);

            // Собственного отрезка трассы у вставки нет намеренно: он создавался бы на
            // каждый инструмент с новыми строками и на каждую страницу загрузки, а исход
            // вставки и число строк несут счётчики, отказ — событие журнала.
            try
            {
                long inserted = await insertOperation(ct).ConfigureAwait(false);

                RecordInsert(in insertContext, MoexOutcomes.Success, inserted);
                return inserted;
            }
            catch (Exception ex)
            {
                ClickHouseWriterLogMessages.WriteFailed(_logger, ex, table, ex.GetType().Name);

                // Обработчик остаётся один: разводить отмену в отдельный catch значило бы
                // лишить её существующего события журнала. Различие видно по типу исключения,
                // и на исход метрики оно влияет, а на журналирование — нет.
                string outcome = ex is OperationCanceledException
                    ? MoexOutcomes.Cancelled
                    : MoexOutcomes.Error;

                // Число вставленных строк не записывается: драйвер его не подтвердил.
                RecordInsert(in insertContext, outcome, null);

                throw;
            }
        }

        private static Dictionary<string, object> CreateFlowSettings(StorageInsertContext insertContext)
        {
            return insertContext.Flow == MoexFlows.History
                ? new Dictionary<string, object>
                {
                    ["async_insert"] = DisabledSetting,
                }
                : new Dictionary<string, object>
                {
                    ["async_insert"] = EnabledSetting,
                    ["wait_for_async_insert"] = EnabledSetting,
                };
        }

        private static void RecordInsert(
            in StorageInsertContext context,
            string outcome,
            long? insertedRows)
        {
            TagList operationTags = new TagList
            {
                { MoexTelemetryAttributes.DataKind, context.DataKind },
                { MoexTelemetryAttributes.Market, context.Market },
                { MoexTelemetryAttributes.Flow, context.Flow },
                { MoexTelemetryAttributes.Outcome, outcome },
            };

            if (context.CandleInterval is int candleInterval)
                operationTags.Add(MoexTelemetryAttributes.CandleInterval, candleInterval);

            MoexMetrics.StorageInsertOperations.Add(1, operationTags);

            // Число строк записывается только при подтверждении драйвером, а подтверждает
            // он его лишь при успехе. Поэтому у счётчика строк метка исхода постоянна;
            // различие исходов несёт счётчик операций строкой выше.
            if (insertedRows is long rows)
                MoexMetrics.StorageInsertRows.Add(rows, operationTags);
        }
    }
}
