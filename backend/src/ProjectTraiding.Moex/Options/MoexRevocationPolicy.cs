using System;
using System.Collections.Generic;
using System.Text;

namespace ProjectTraiding.Moex.Options
{
    /// <summary>
    /// Политика проверки отзыва сертификатов для соединений с Московской биржей.
    /// Параметр среды, а не свойство источника: точки распространения списков отзыва
    /// у НУЦ Минцифры расположены на российских адресах, и их доступность зависит от
    /// того, откуда работает приложение.
    /// </summary>
    public enum MoexRevocationPolicy
    {
        /// <summary>Отзыв не проверяется. Совпадает с поведением проекта до этой правки.</summary>
        Off,

        /// <summary>
        /// Отзыв проверяется по сети. Если статус установить не удалось, соединение
        /// разрешается. Сертификат, который точно помечен отозванным, всё равно отвергается.
        /// Цена режима: тот, кто способен заблокировать доступ к спискам отзыва, тем самым
        /// скрывает отзыв. Для загрузчика биржевых данных принято как приемлемое.
        /// </summary>
        SoftFail,

        /// <summary>Отзыв проверяется по сети. Неопределённый статус означает отказ.</summary>
        Strict
    }
}
