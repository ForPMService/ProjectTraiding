namespace ProjectTraiding.Moex.Series;

/// <summary>
/// Итог разбора одной страницы источника.
///
/// Rows — принятые строки. SourceRowsCount — сколько строк ответа эта страница
/// представляет: принятые плюс отвергнутые. SkippedSourceRows — отвергнутые строки
/// внутри страницы, по возрастанию позиции; пусто, когда отвергнутых нет.
///
/// Отвергнутые строки хранятся, а не только их число, потому что пагинация продолжает
/// чтение по смещению в ответе источника. Длина списка принятых строк смещением быть
/// перестала: между двумя принятыми строками может оказаться отвергнутая.
///
/// Пустой перечень выражен отсутствующим списком, а не пустым: отвергнутая строка —
/// редкость, и на обычном пути лишнего списка на каждую страницу не возникает.
/// </summary>
public readonly record struct SeriesParsedPage(
    List<(object?[] Row, DateTime Time)> Rows,
    int SourceRowsCount,
    List<SkippedSourceRow>? SkippedSourceRows)
{
    public int SkippedRows => SkippedSourceRows?.Count ?? 0;
}

/// <summary>
/// Отвергнутая строка: её позиция в ответе источника и момент, если его удалось
/// прочитать. Момент нужен для рядов, у которых страница не должна рассекать группу
/// строк одного времени: без него отвергнутая строка не отличима от строки соседней
/// группы, и границу пришлось бы искать вслепую.
/// </summary>
public readonly record struct SkippedSourceRow(int SourceIndex, DateTime? Time);
