-- Запрос оператора на остановку выполняющегося задания. Признак обрабатывает
-- живой координатор загрузки; итог зависит от того, был ли запрос зафиксирован
-- до его последней проверки перед записью покрытия.

ALTER TABLE moex_load_tasks
    ADD COLUMN cancel_requested_at timestamptz NULL;

COMMENT ON COLUMN moex_load_tasks.cancel_requested_at IS
    'Момент запроса оператора на остановку выполняющегося задания. Фактический итог зависит от того, успел ли запрос до последней проверки координатора перед записью покрытия';

COMMENT ON COLUMN moex_load_tasks.status IS
    'pending, running, done, error, partial, cancelled. cancelled — снято оператором командой Management: для pending это отказ до запуска, для partial — отказ от дальнейшего выполнения, для running — итог фактической остановки координатором. По прежнему идентификатору не возобновляется, для повторной загрузки создаётся новое задание';
