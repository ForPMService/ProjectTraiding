-- Универсальная таблица корпоративных событий удаляется.
--
-- Пять типов событий делили один набор дивидендных колонок и ни один процесс не
-- описывали целиком. Дивидендные события вводятся отдельной таблицей следующей
-- миграцией; сущности процесса не появляется. Автоматическое преобразование запрещено: у meeting, issue, buyback и
-- delisting_announced однозначного соответствия дивидендным этапам нет.

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM moex_manual_events) THEN
        RAISE EXCEPTION
            'moex_manual_events содержит строки. Автоматическое преобразование в новую модель запрещено. Миграция остановлена; требуется решение владельца по существующим данным.';
    END IF;
END $$;

DROP TABLE moex_manual_events;
