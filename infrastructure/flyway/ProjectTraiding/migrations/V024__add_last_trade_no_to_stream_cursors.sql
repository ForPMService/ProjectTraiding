-- V024: Отметка последней принятой сделки в курсоре приёма.
--
-- Задача. moex_stream_cursors.last_source_time (V019) хранит рыночное время докуда принято.
-- Для ленты сделок этого мало по двум причинам, установленным замером 13.07.2026:
--   1. До 427 сделок в одну секунду при точности времени источника в секунду. Отметка
--      "принято до 18:58:11" не говорит, приняты ли все 427 сделок этой секунды или часть.
--   2. Биржа принимает курсор по TRADENO (tradeno=...&next_trade=1), а не по времени.
--      Чтобы продолжить приём, нужен последний номер сделки — время его не заменяет.
--
-- last_trade_no заполняется только для ленты сделок. У стакана и свечей остаётся пустым:
-- там ключ по времени достаточен, номера сделок нет.
--
-- База курсоров пуста — добавление столбца безопасно.

ALTER TABLE moex_stream_cursors
    ADD COLUMN last_trade_no bigint;

COMMENT ON COLUMN moex_stream_cursors.last_trade_no IS
    'Номер последней принятой сделки (TRADENO). Только для ленты сделок; у стакана и свечей NULL. Курсор биржи: tradeno + next_trade=1';

-- Комментарий data_kind из V019 не знал видов реального времени. Дополняем.
COMMENT ON COLUMN moex_stream_cursors.data_kind IS
    'История: candles, tradestats, obstats, orderstats, futoi, hi2, mega_alerts. Приём: trades, orderbook, candles';