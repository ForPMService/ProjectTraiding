-- Пропущенные строки: сколько строк ответа источника отвергнуто разбором при загрузке
-- диапазона. Столбец нужен ровно затем, чтобы полнота покрытия не была молчаливой:
-- диапазон со статусом 'ok' и ненулевым числом пропусков загружен не целиком.
ALTER TABLE moex_loaded_ranges
    ADD COLUMN rows_skipped bigint NOT NULL DEFAULT 0;

COMMENT ON COLUMN moex_loaded_ranges.rows_skipped IS
    'Число строк, отвергнутых разбором при загрузке диапазона. Ненулевое значение означает неполное покрытие при статусе ok: исходные строки не сохраняются, повторная загрузка того же диапазона отвергнет их снова';
